#  FUNZIONE PER SCRIVERE I DATI DEL BATCH SU POSTGRESQL
def write_to_postgres(batch_df, batch_id):

    if batch_df.isEmpty():
        return # return nothing

    insert_df   = batch_df.filter(col("op") == "c")
    update_df   = batch_df.filter(col("op") == "u")
    snapshot_df = batch_df.filter(col("op") == "r")
    delete_df   = batch_df.filter(col("op") == "d")
  

    # Prepariamo i dati per le operazioni UPSERT, che saranno sottoposti a un'ulteriore fase di filtraggio nel DataFrame "upsert_df", definito più avanti.
    upsert_source_df = (
        insert_df
        .unionByName(update_df)
        .unionByName(snapshot_df)
    ) # Combiniamo insert + update + snapshot in un unico dataframe. cosi evitiamo code redundance


    # Filtriamo i dati UPSERT prima di inserirli nel database di destinazione (sink). (dettagli in descrizione)
    upsert_df = ( 
        upsert_source_df # 
        .filter(col("role") == "ADMIN") # Solo ADMINs records per insert/update su destination db
        .withColumn("updated_ts", to_timestamp(col("updatedAt") / 1000)) # withColumn crea una colonna temporanea che possiamo usare come riferimento, come facciamo sotto
        .dropDuplicates(["id", "updated_ts"]) # si basa su payload "after" data.  
        # “Se Kafka mi manda due volte lo stesso evento CDC (stesso id + stesso timestamp), ne tengo solo uno.” (Perfetto quando si usa CDC Debezium, perche a volte si crea lo stesso evento 2 o piu' volte)
        # questo non conta per update(non viene bloccato), perche' avremo lo stesso id, ma update_ts diverso
    )
       
       
    # Rimuoviamo le colonne CDC e tecniche prima della scrittura nel database di destinazione. (dettagli in descrizione)
    upsert_df = upsert_df.drop("op", "before_id", "_corrupt_record", "updated_ts") # cosi' restano solo le colonne che spark 
        # va' ad inserire nel sink db
   
    # --- PREPARE DATA ---
    upsert_rows = [
        (r.id, r.email, r.name, r.password, r.role, r.updatedAt)
        for r in upsert_df.select(
            "id", "email", "name", "password", "role", "updatedAt"
        ).collect()
    ]

    delete_ids = [
        r.before_id
        for r in delete_df.select("before_id").dropna().distinct().collect()
    ]


    if not upsert_rows and not delete_ids:
        return

    
    # UPSERT/DELETE DATA IN SINK DB.
    if upsert_rows or delete_ids: 
        # in upsert_df arrivano i dati di cdc_df definiti in 'query'(sotto) quando chiamiamo la funzione write_to_postgres()

        # --- DB TRANSACTION (1 BATCH = 1 TRANSACTION) --- (dettagli in descrizione)
        conn = psycopg2.connect(db_url)
        conn.autocommit = False
        cur = conn.cursor()

        try:
        # UPSERT (INSERT / UPDATE)
        # Costruiamo la query UPSERT. Per revitare errors quando facciamo un update dei dati (dettagli in descrizione)
            if upsert_rows:
                  # Idempotenza garantita 
                  upsert_query = """
                    INSERT INTO employee_admin (id, email, name, password, role, updatedAt)
                    VALUES (%s, %s, %s, %s, %s, %s)
                    ON CONFLICT (id) DO UPDATE
                    SET email = EXCLUDED.email,
                        name = EXCLUDED.name,
                        password = EXCLUDED.password,
                        role = EXCLUDED.role,
                        updatedAt = EXCLUDED.updatedAt;
                   """ # nella upsert_query qui sopra, ON CONFLICT (id) DO UPDATE assicura Idempotenza garantita e 
                       # niente duplicati a causa di un crasch di spark e rilettura dei topic kafka gia processati ma non salvati nel file checkpoint
                  
                  execute_batch(cur, upsert_query, upsert_rows, page_size=100) # per eseguire batch di dati in modo veloce e' sicuro

        # DELETE. 
            if delete_ids:
               
               cur.execute(
                  "DELETE FROM employee_admin WHERE id = ANY(%s);",
                  (delete_ids,)
               )

        # ✅ COMMIT SOLO QUI(un solo commit per batch di upsert e delete). se spark crasha prima fare il commit, avviene il rollback,
        #  il checkpoint non si aggiorna, e retry sicuro.(100% Exactly once principle) 
            conn.commit()
            # print("Records da eliminare:", delete_ids)

            
        except Exception as e:
            # TUTTO ANNULLATO SE QUALCOSA VA STORTO
            conn.rollback()
            raise e # errore di exeption
        finally:
            cur.close()
            conn.close()

# Combiniamo valid_df e delete_df per passare entrambi i DataFrame alla funzione write_to_postgres(), 
# che gestisce le operazioni sul database di destinazione.
cdc_df = valid_df.unionByName(delete_df, allowMissingColumns=True)

query = (
    cdc_df # Per ogni nuova operazione INSERT, DELETE o UPDATE, passiamo i dati alla funzione write_to_postgres, che esegue le operazioni CRUD in batch sul database PostgreSQL di destinazione.
    .writeStream
    .foreachBatch(write_to_postgres) # foreachBatch ci permette logica custom (UPSERT / DELETE) e checkpoint gestito da Spark
    .option("checkpointLocation", "/tmp_spark/checkpoint") # Spark sa da dove ripartire. offset Kafka + stato streaming salvati (usa s3 in produzione)
    .start()
) # 

query.awaitTermination()

